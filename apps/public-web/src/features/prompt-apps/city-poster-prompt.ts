export type CityPosterPromptInput = Readonly<{
  city: string;
  note: string;
}>;

const CITY_POSTER_TEMPLATE = `---

请根据【城市】生成一张充满新春喜庆氛围但不失高雅格调的 2026 城市宣传海报。

画面采用双重曝光，构图延续 S 型的流动感；在纯白的纹理背景右下角，一个身穿中国传统服饰的微缩人物正在挥舞着一条长长的红色丝绸舞带。这条红绸在空中舞动，不仅展现出丝绸的柔顺质感，更在向左上方飘动的过程中，奇幻地变形成一条壮丽的山脉河流。

在这条“河流”中，叠加一个根据【城市】自动生成的城市手绘图，国潮风格，要求把该城市最具代表性的山水格局、河流湖海、天际线、历史建筑、现代地标、城市街区和文化符号自然融合。根据【城市】自动选取代表性地标，并优先吸收【备注】中指定的地点、景观、宣传重点或城市气质。

画面需要呈现有山、有水、有城市肌理的壮阔视野，景色尽在眼底，雄伟但不拥挤，令人震撼。云雾环绕，仙气缥缈，色彩丰富，结构复杂，细节丰富，但因为大面积留白，画面依然显得清新脱俗。

左下角排版 “SPRING 2026”，并加入一条竖排城市宣传语。宣传语应根据【城市】的核心定位、文化气质和【备注】自动生成，文字排版优美、大方、字迹清晰完整，整体寓意该城市的时代活力、文化底蕴和旅游传播价值。

整体风格：国潮、城市手绘、东方审美、双重曝光、红绸水墨、精致纸张纹理、高级留白、云雾仙气、丰富但克制的节庆色彩。尺寸 9:16。`;

export function buildCityPosterPrompt(input: CityPosterPromptInput) {
  const city = input.city.trim();
  const note = input.note.trim();
  const cityLine = note ? `【城市】= {${city}}（${note}）` : `【城市】= {${city}}`;
  return `${cityLine}\n\n${CITY_POSTER_TEMPLATE}`;
}
